#pragma once
// =============================================================================
// Material.h — 面の質感 (金属・粗さの流儀の PBR)
//
// プリミティブの面をどう光らせるかの値。 部品 (IceComponent など) がセッター・ゲッターで読み書きし、
// 描くときにシェーダーの定数へ写す。 解説: docs/03-ice-component.md 「面の色 (PBR)」
// =============================================================================

#include "MathTypes.h"

struct Material {
    // 下地の色 (RGBA、 0〜1)。 金属でなければ拡散反射の色、 金属なら映り込みの色。 a は不透明度 (今は使わない)
    Float4 baseColor = { 1.0f, 1.0f, 1.0f, 1.0f };

    float metallic = 0.0f;   // 金属らしさ (0 = 金属でない、 1 = 金属)
    float roughness = 0.5f;  // 表面の粗さ (0.04〜1。 0 に近いほど鏡のよう)
    float specular = 0.5f;   // 金属でない面の、 正面から見た反射の強さ。 F0 = 0.08 × specular (0.5 で 4%)
};
