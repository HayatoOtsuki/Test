#pragma once
// =============================================================================
// DirectionalLight.h — 平行光源 (太陽)
//
// とても遠くにある光源。 どこから見ても同じ向きから、 同じ強さで光が来る。
// Application が持ち、 Renderer が毎フレーム シーンの定数 (SceneConstants) に書いてシェーダーへ渡す。
// シェーダーには太陽の向きや色の数字を書かない (ハードコードしない)。
// =============================================================================

#include "MathTypes.h"

struct DirectionalLight {
    // 面から光源へ向かう向き (長さ 1)。 光が進む向きの逆なので注意。
    // 初めは高さ約 30°、 初めのカメラから見て奥 (-x, -z の側)。 氷が逆光で光り、 影は手前に落ちる
    Float3 direction = normalize(Float3{ -0.5f, 0.45f, -0.6f });

    Float3 color = { 1.0f, 0.95f, 0.88f };  // 光の色 (白より少し黄色寄り)
    float intensity = 1.8f;                 // 強さ。 白い面を真上から照らしたときの明るさ
};
